import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
const app = resolve(Bun.argv[2] ?? "public/starter/app");
const parser = resolve(Bun.argv[3] ?? app, "node_modules/typescript/lib/typescript.js");
if (!existsSync(parser)) throw new Error(`缺少 TypeScript 解析器：${parser}`);
const ts = await import(pathToFileURL(parser).href);
const componentPath = resolve(app, "src/LoginPage.tsx");
const text = await readFile(componentPath, "utf8");
const source = ts.createSourceFile(componentPath, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const imports: Array<{ name: string; module: string }> = [];
const calls = new Set<string>(); let detail = false;
const visit = (node: any): void => { if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier) && node.importClause?.namedBindings && ts.isNamedImports(node.importClause.namedBindings)) for (const item of node.importClause.namedBindings.elements) imports.push({ name: item.name.text, module: node.moduleSpecifier.text }); if (ts.isCallExpression(node) && ts.isIdentifier(node.expression)) calls.add(node.expression.text); if (ts.isPropertyAccessExpression(node) && ["status", "body"].includes(node.name.text)) detail = true; ts.forEachChild(node, visit); };
visit(source);
const failures: string[] = [];
if (imports.some((entry) => entry.module.includes("services/http"))) failures.push("组件不得直接依赖 HTTP adapter。");
if (detail) failures.push("组件不得读取原始 response 的 status 或 body。");
const boundary = (await Promise.all(imports.filter((entry) => calls.has(entry.name) && entry.module.startsWith(".")).map(async (entry) => { const base = resolve(dirname(componentPath), entry.module); for (const path of [`${base}.ts`, `${base}.tsx`, resolve(base, "index.ts")]) if (existsSync(path)) return await readFile(path, "utf8"); return undefined; }))).find((value): value is string => Boolean(value) && /services\/http/.test(value) && /\.status/.test(value));
if (!boundary) failures.push("查询路径必须调用组件外边界并由其负责 transport。");
else if (!/\b(kind|state):\s*["'](ready|empty|failed)["']/.test(boundary)) failures.push("查询边界必须返回显式资源状态。");
console.log(JSON.stringify({ passed: failures.length === 0, failures }, null, 2));
process.exit(failures.length ? 1 : 0);
